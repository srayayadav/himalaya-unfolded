 # 0 hook
 ["There is a famous saying, often attributed to an Indian field marshal.",
  "If a man says he is not afraid of dying, he is either lying, or he is a Gurkha.",
  "For more than two hundred years, soldiers from the hills of Nepal have fought in Britain's wars.",
  "Thirteen Nepali Gurkhas have won the Victoria Cross, Britain's highest award for bravery."],
 # 1 title
 ["So who are the Gurkhas, and why did armies fear them?"],
 # 2 map: Gorkha
